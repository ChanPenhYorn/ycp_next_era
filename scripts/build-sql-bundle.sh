#!/usr/bin/env bash
#
# Concatenates the migrations into one file that can be pasted straight into the
# Supabase SQL editor, for when running the CLI is not convenient.
#
#   ./scripts/build-sql-bundle.sh
#
# Output: supabase/bundle/combined.sql
#
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
# Deliberately NOT in supabase/migrations: `supabase db push` applies every
# .sql in that folder, and the bundle contains all of them already.
OUT="$ROOT/supabase/bundle/combined.sql"

{
  cat <<'HEADER'
-- ============================================================================
-- Chanpenh - complete schema, RLS and business logic.
--
-- Generated by scripts/build-sql-bundle.sh. Do not edit by hand.
--
-- Paste this whole file into the Supabase SQL editor and run it once against a
-- fresh project. It is idempotent enough to re-run: every object is created
-- with `if not exists` or `create or replace`.
--
-- Order matters. The sections below are the individual migrations concatenated
-- in the same order the CLI would apply them.
-- ============================================================================
HEADER

  for migration in "$ROOT"/supabase/migrations/*.sql; do
    name="$(basename "$migration")"
    printf '\n\n-- ============================================================================\n'
    printf -- '-- %s\n' "$name"
    printf -- '-- ============================================================================\n\n'
    # A progress notice, so a failure in a 2000-line paste can be located
    # instead of leaving you to guess which section died.
    printf "do \$\$ begin raise notice '>>> %s'; end \$\$;\n\n" "$name"
    cat "$migration"
  done
} > "$OUT"

lines=$(wc -l < "$OUT" | tr -d ' ')
printf 'wrote %s (%s lines)\n' "$OUT" "$lines"
